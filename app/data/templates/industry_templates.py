def get_industry_template(industry: str = "general") -> dict:
    """获取行业模板配置"""
    template_path = os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "industry_templates.json"
    )
    
    if os.path.exists(template_path):
        with open(template_path, "r", encoding="utf-8") as f:
            templates = json.load(f)
            return templates.get(industry, templates.get("general", {}))
    
    return {}


def get_industry_list() -> list:
    """获取所有可用行业列表"""
    template_path = os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "industry_templates.json"
    )
    
    if os.path.exists(template_path):
        with open(template_path, "r", encoding="utf-8") as f:
            templates = json.load(f)
            return [{"key": k, "name": v.get("name", k), "description": v.get("description", "")} 
                    for k, v in templates.items()]
    
    return [{"key": "general", "name": "通用", "description": "通用行业模板"}]